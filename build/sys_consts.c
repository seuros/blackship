/*
 * Emits the FreeBSD ioctl request codes and driver subcommands used by
 * src/network/ioctl.rs as Rust constants. The SIOC* values come from
 * _IOW()/_IOWR() macros, which bindgen does not expand, so they are printed
 * from a C program that includes the real headers instead of being
 * transcribed by hand.
 */

#include <sys/types.h>
#include <sys/ioccom.h>
#include <sys/sockio.h>
#include <sys/procctl.h>
#include <net/if.h>
#include <net/if_bridgevar.h>
#include <netgraph/ng_message.h>
#include <netgraph/ng_bridge.h>
#include <netgraph/ng_eiface.h>
#include <stdio.h>

int main(void) {
	puts("// @generated by build/sys_consts.c -- do not edit.");
	puts("use libc::{c_int, c_ulong};");
	puts("");

#define EMIT_ULONG(name) \
	printf("pub const %s: c_ulong = 0x%lx;\n", #name, (unsigned long)(name))
#define EMIT_INT(name) \
	printf("pub const %s: c_int = %d;\n", #name, (int)(name))

	/* <sys/sockio.h> -- interface ioctls */
	EMIT_ULONG(SIOCSDRVSPEC);
	EMIT_ULONG(SIOCGDRVSPEC);
	EMIT_ULONG(SIOCIFCREATE2);
	EMIT_ULONG(SIOCIFDESTROY);
	EMIT_ULONG(SIOCGIFFLAGS);
	EMIT_ULONG(SIOCSIFFLAGS);
	EMIT_ULONG(SIOCSIFNAME);
	EMIT_ULONG(SIOCSIFLLADDR);
	EMIT_ULONG(SIOCSIFVNET);
	EMIT_ULONG(SIOCAIFADDR);
	EMIT_ULONG(SIOCGIFCAP);
	EMIT_ULONG(SIOCSIFCAP);

	/* <net/if.h> -- capability bits */
	EMIT_INT(IFCAP_VLAN_HWFILTER);

	/* <net/if_bridgevar.h> -- if_bridge driver subcommands */
	EMIT_ULONG(BRDGADD);
	EMIT_ULONG(BRDGDEL);
	EMIT_ULONG(BRDGGIFS);
	EMIT_ULONG(BRDGSIFPVID);
	EMIT_ULONG(BRDGSIFVLANSET);
	EMIT_ULONG(BRDGGFLAGS);
	EMIT_ULONG(BRDGSFLAGS);

	/* Struct sizes ioctl.rs asserts against. */
	printf("pub const SIZEOF_IFBREQ: usize = %zu;\n", sizeof(struct ifbreq));
	printf("pub const SIZEOF_IFBIFCONF: usize = %zu;\n",
	    sizeof(struct ifbifconf));
	printf("pub const SIZEOF_IFBRPARAM: usize = %zu;\n",
	    sizeof(struct ifbrparam));

#define EMIT_USIZE(name) \
	printf("pub const %s: usize = %zu;\n", #name, (size_t)(name))

	/* <netgraph/ng_message.h> -- name buffer sizes */
	EMIT_USIZE(NG_HOOKSIZ);
	EMIT_USIZE(NG_TYPESIZ);
	EMIT_USIZE(NG_NODESIZ);

	/* <netgraph/ng_message.h> -- generic control messages */
	EMIT_INT(NGM_GENERIC_COOKIE);
	EMIT_INT(NGM_SHUTDOWN);
	EMIT_INT(NGM_MKPEER);
	EMIT_INT(NGM_RMHOOK);
	EMIT_INT(NGM_LISTHOOKS);

	/* <netgraph/ng_bridge.h>, <netgraph/ng_eiface.h> */
	EMIT_INT(NGM_BRIDGE_COOKIE);
	EMIT_INT(NGM_BRIDGE_SET_PERSISTENT);
	EMIT_INT(NGM_EIFACE_COOKIE);
	EMIT_INT(NGM_EIFACE_GET_IFNAME);

	/*
	 * netgraph struct sizes. ng_mesg ends in a flexible array member, so
	 * sizeof() is exactly the header length netgraph.rs needs.
	 */
	printf("pub const SIZEOF_NG_MESG_HEADER: usize = %zu;\n",
	    sizeof(struct ng_mesg));
	printf("pub const SIZEOF_NGM_MKPEER: usize = %zu;\n",
	    sizeof(struct ngm_mkpeer));
	printf("pub const SIZEOF_NGM_RMHOOK: usize = %zu;\n",
	    sizeof(struct ngm_rmhook));
	printf("pub const SIZEOF_NODEINFO: usize = %zu;\n",
	    sizeof(struct nodeinfo));
	printf("pub const SIZEOF_LINKINFO: usize = %zu;\n",
	    sizeof(struct linkinfo));

	/* <sys/procctl.h> -- reaper subtree kill */
	printf("pub const REAPER_KILL_SUBTREE: u32 = %u;\n",
	    (unsigned)REAPER_KILL_SUBTREE);
	printf("pub const SIZEOF_PROCCTL_REAPER_KILL: usize = %zu;\n",
	    sizeof(struct procctl_reaper_kill));

	return ferror(stdout) ? 1 : 0;
}
