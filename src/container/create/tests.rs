use super::*;
use crate::container::{Limits, Mount};

#[test]
fn default_spec_has_no_network_and_persists() {
    let spec = ContainerSpec::new("kim-1", "16.0-CURRENT");
    let params = jail_params(&spec, Path::new("/c/kim-1"));
    assert_eq!(
        params,
        [
            "name=kim-1",
            "path=/c/kim-1",
            "host.hostname=kim-1",
            "persist",
            "mount.devfs",
            "ip4=disable",
            "ip6=disable",
        ]
    );
}

#[test]
fn spec_knobs_map_to_jail_params() {
    let spec = ContainerSpec::new("kim-2", "16.0-CURRENT")
        .hostname("ci")
        .network(Network::Inherit)
        .allow_raw_sockets()
        .allow_chflags()
        .boot()
        .jail_param("allow.mlock");
    let params = jail_params(&spec, Path::new("/c/kim-2"));
    for expected in [
        "host.hostname=ci",
        "ip4=inherit",
        "ip6=inherit",
        "allow.raw_sockets",
        "allow.chflags",
        "exec.start=/bin/sh /etc/rc",
        "allow.mlock",
    ] {
        assert!(params.iter().any(|p| p == expected), "missing {expected}");
    }

    let vnet = ContainerSpec::new("kim-3", "r").network(Network::vnet("ci"));
    assert!(
        jail_params(&vnet, Path::new("/c"))
            .iter()
            .any(|p| p == "vnet")
    );
}

#[test]
fn validate_rejects_bad_names_hosts_and_mounts() {
    let ok = ContainerSpec::new("kim-1", "16.0-CURRENT");
    validate(&ok).unwrap();

    for bad in [
        ContainerSpec::new("kim.1", "16.0-CURRENT"),
        ContainerSpec::new("kim/1", "16.0-CURRENT"),
        ContainerSpec::new("kim-1", "../etc"),
        ok.clone().hostname("bad host"),
        ok.clone().mount(Mount::read_only("relative", "/x")),
        ok.clone().mount(Mount::read_only("/tmp", "relative")),
        ok.clone().mount(Mount::read_only("/tmp", "/a/../../etc")),
        ok.clone().mount(Mount::read_only("/tmp", "/")),
        ok.clone().jail_param("-r"),
    ] {
        assert!(validate(&bad).is_err(), "accepted {bad:?}");
    }

    validate(&ok.mount(Mount::read_write("/tmp", "/work"))).unwrap();
}

#[test]
fn limits_feed_the_rctl_config() {
    let limits = Limits::new()
        .memory("4g")
        .cpu_percent(200)
        .max_processes(512)
        .cpus("0-3");
    let resources = limits.resources();
    assert_eq!(resources.memory.as_deref(), Some("4g"));
    assert_eq!(resources.cpu.as_deref(), Some("200"));
    assert_eq!(resources.maxproc, Some(512));
    assert_eq!(resources.cpuset.as_deref(), Some("0-3"));
    assert!(resources.has_rctl_rules());
    assert!(Limits::new().is_empty());
}

const LAN: &str = "# Generated by resolvconf\nsearch home.local\nnameserver 192.168.3.5\n";
const UNBOUND: &str = "nameserver 127.0.0.1\nnameserver ::1\noptions edns0\n";

#[test]
fn vnet_containers_get_the_hosts_resolver() {
    let spec = ContainerSpec::new("ci-1", "16.0-CURRENT").network(Network::vnet("default"));
    assert_eq!(resolv_conf(&spec, Some(LAN)).unwrap().as_deref(), Some(LAN));
    // A host without a resolver has nothing to hand on.
    assert_eq!(resolv_conf(&spec, None).unwrap(), None);
}

#[test]
fn vnet_containers_drop_nameservers_only_the_host_can_reach() {
    let spec = ContainerSpec::new("ci-1", "16.0-CURRENT").network(Network::vnet("default"));
    let mixed = "nameserver 127.0.0.1\nnameserver fe80::1%bge0\nnameserver 192.168.3.5\n";
    assert_eq!(
        resolv_conf(&spec, Some(mixed)).unwrap().as_deref(),
        Some("nameserver 192.168.3.5\n")
    );
    match resolv_conf(&spec, Some(UNBOUND)) {
        Err(Error::Network(message)) => assert!(message.contains("127.0.0.1, ::1"), "{message}"),
        other => panic!("expected a Network error, got {other:?}"),
    }
}

#[test]
fn inherit_shares_the_hosts_file_verbatim_and_none_leaves_the_release_alone() {
    let inherit = ContainerSpec::new("ci-1", "r").network(Network::Inherit);
    assert_eq!(
        resolv_conf(&inherit, Some(UNBOUND)).unwrap().as_deref(),
        Some(UNBOUND)
    );
    let none = ContainerSpec::new("ci-1", "r");
    assert_eq!(resolv_conf(&none, Some(LAN)).unwrap(), None);
}

#[test]
fn explicit_nameservers_win() {
    let spec = ContainerSpec::new("ci-1", "r")
        .network(Network::vnet("default"))
        .nameserver([9, 9, 9, 9])
        .nameserver("2620:fe::fe".parse::<IpAddr>().unwrap());
    assert_eq!(
        resolv_conf(&spec, Some(UNBOUND)).unwrap().as_deref(),
        Some("# Written by blackship\nnameserver 9.9.9.9\nnameserver 2620:fe::fe\n")
    );
}
